package com.poketch.core.domain.model

/**
 * Pixel-perfect GBA FireRed sprite metrics for all 151 Kanto Pokémon.
 * Enables precise ground alignment, anti-floating padding elimination,
 * anti-oversize scaling, and authentic battle arena positioning.
 */
data class PokemonSpriteMetrics(
    val backTopPad: Int,
    val backBottomPad: Int,
    val backLeftPad: Int,
    val backRightPad: Int,
    val frontTopPad: Int,
    val frontBottomPad: Int,
    val frontLeftPad: Int,
    val frontRightPad: Int,
    val isFlying: Boolean = false,
) {
    val backContentHeight: Int get() = 64 - backTopPad - backBottomPad
    val backContentWidth: Int get() = 64 - backLeftPad - backRightPad
    val frontContentHeight: Int get() = 64 - frontTopPad - frontBottomPad
    val frontContentWidth: Int get() = 64 - frontLeftPad - frontRightPad

    /** Scale factor for Buddy (back sprite) to prevent oversize/clipping issues */
    val buddyScaleFactor: Float
        get() = when {
            backContentHeight >= 61 -> 0.82f
            backContentHeight >= 56 -> 0.90f
            else -> 1.0f
        }

    /** Scale factor for Wild Target (front sprite) */
    val wildScaleFactor: Float
        get() = when {
            frontContentHeight >= 61 -> 0.80f
            frontContentHeight >= 56 -> 0.88f
            else -> 1.0f
        }
}

